//! Ядро экосистемы: мир, особи, их «мозги» и один шаг симуляции.
//!
//! Ядро ничего не знает об отрисовке и об интерфейсе — тот же код работает
//! в окне и в пакетных прогонах автонастройки, где рисовать не нужно.
//!
//! Два свойства считаются обязательными и закреплены тестами:
//!
//! * **Сохранение массы.** Биомасса не возникает и не исчезает. Она лежит
//!   в трёх пулах клетки (растения, падаль, питательные вещества) и в энергии
//!   особей; сумма этих четырёх величин неизменна весь прогон.
//! * **Детерминизм.** Один сид даёт побитово один и тот же прогон: порядок
//!   применения действий фиксирован, генератор случайных чисел свой,
//!   системный `tanh` заменён аппроксимацией.


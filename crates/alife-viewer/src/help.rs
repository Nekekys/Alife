//! Пояснение происходящего прямо в окне.
//!
//! Числа берутся из живого конфига, а не зашиты в текст: иначе пояснение
//! разойдётся с симуляцией на первой же правке параметров.

use alife_core::Sim;
use eframe::egui::{self, Color32, Sense, Vec2};

use crate::colors::{cell_color, diet_color};
use crate::worldview::ColorMode;

/// Компактная легенда под картой: что означают цвета прямо сейчас.
pub fn legend(ui: &mut egui::Ui, mode: ColorMode, resources: bool, agents: bool) {
    ui.horizontal_wrapped(|ui| {
        ui.spacing_mut().item_spacing.x = 6.0;
        if resources {
            swatch(ui, cell_color(0.9, 0.0, 0.2), "растения");
            swatch(ui, cell_color(0.0, 0.9, 0.2), "падаль");
            swatch(ui, cell_color(0.0, 0.0, 1.0), "питательные вещества");
            swatch(ui, cell_color(0.0, 0.0, 0.0), "пусто");
            ui.separator();
        }
        if !agents {
            ui.small("особи не показаны");
            return;
        }
        match mode {
            ColorMode::Diet => {
                swatch(ui, diet_color(1.0, 0.0, 0.0), "травоядная");
                swatch(ui, diet_color(0.0, 1.0, 0.0), "хищная");
                swatch(ui, diet_color(0.0, 0.0, 1.0), "съела мало, судить рано");
            }
            ColorMode::Lineage => {
                ui.small("особи: цвет по линии — родственники одного оттенка");
            }
            ColorMode::Energy => {
                ui.small("особи: от синего к белому по энергии");
            }
            ColorMode::Age => {
                ui.small("особи: от синего к белому по возрасту");
            }
            ColorMode::Generation => {
                ui.small("особи: от синего к белому по поколению");
            }
        }
    });
}

fn swatch(ui: &mut egui::Ui, color: Color32, label: &str) {
    let (rect, _) = ui.allocate_exact_size(Vec2::new(14.0, 14.0), Sense::hover());
    ui.painter().rect_filled(rect, 2.0, color);
    ui.small(label);
}

/// Вкладка «Что происходит».
pub fn show(ui: &mut egui::Ui, sim: &Sim) {
    let cfg = &sim.cfg;
    let a = &cfg.agent;
    let r = &cfg.resources;
    let cells = sim.world.w * sim.world.h;

    ui.heading("Что здесь происходит");
    ui.label(
        "Это экосистема без цели. Никто не считает, насколько особь хороша, \
         и не отбирает лучших: особь просто живёт, ест, размножается и умирает \
         по своей энергии. Выживает то поведение, которое оставляет больше потомков. \
         Мир никогда не сбрасывается и не делится на эпохи.",
    );
    ui.add_space(4.0);
    ui.label(
        "Поведением управляет нейросеть внутри каждой особи. При рождении потомок \
         получает копию сети родителя со случайным шумом в весах — это и есть вся \
         эволюция. Скрещивания нет.",
    );

    ui.add_space(8.0);

    section(ui, "Мир и масса", |ui| {
        ui.label(format!(
            "Поле {}x{} клеток ({cells} клеток), замкнутое в тор: уходя за правый край, \
             попадаешь на левый. В клетке живёт не больше одной особи.",
            sim.world.w, sim.world.h
        ));
        ui.add_space(4.0);
        ui.label(
            "Биомасса не берётся из ниоткуда и никуда не девается. Она лежит в четырёх местах:",
        );
        bullet(ui, "растения — то, что можно съесть, растут сами");
        bullet(ui, "падаль — остатки погибших, съедаются первыми, иначе разлагаются");
        bullet(ui, "питательные вещества — несъедобный пул, из него растут растения");
        bullet(ui, "энергия внутри самих особей");
        ui.add_space(4.0);
        ui.label(format!(
            "Сумма этих четырёх величин постоянна весь прогон и равна {:.0}. \
             Строка «уход массы» в управлении показывает, насколько она уплыла: \
             это ошибка округления, и она должна оставаться крошечной.",
            sim.initial_mass()
        ));
        ui.add_space(4.0);
        ui.label(
            "Поэтому мир сам себя ограничивает. Съеденное возвращается обратно через \
             дыхание и смерть, и численность упирается не в выдуманный лимит, \
             а в то, сколько масса успевает обернуться.",
        );
    });

    section(ui, "Из чего состоит один шаг", |ui| {
        numbered(ui, 1, "Все живые особи одновременно смотрят вокруг и решают, что делать. Мир в этот момент только читается.");
        numbered(ui, 2, "Решения применяются по очереди, строго по номеру слота: атака, движение, еда, размножение.");
        numbered(ui, 3, "Все платят за жизнь энергией, и кто исчерпал её — умирает.");
        numbered(ui, 4, "Среда делает своё: падаль разлагается, растения растут, питательные вещества растекаются.");
        ui.add_space(4.0);
        ui.label(
            "Порядок второго пункта зафиксирован намеренно. Из-за него один и тот же \
             сид даёт в точности один и тот же прогон — иначе нельзя было бы сравнивать, \
             что изменила правка параметра.",
        );
    });

    section(ui, "Что особь видит", |ui| {
        ui.label(format!(
            "Окно {side}x{side} клеток вокруг себя, по четырём каналам сразу: \
             сколько в клетке растений, падали, питательных веществ и сколько энергии \
             у того, кто там стоит. Это {n} чисел.",
            side = sim.sensor.side,
            n = sim.sensor.side * sim.sensor.side * 4
        ));
        ui.add_space(4.0);
        ui.label(
            "Плюс восемь чисел о себе: своя энергия, возраст, ела ли на прошлом шаге, \
             били ли её, насколько тесно вокруг, что лежит под собой, и постоянная единица.",
        );
        ui.add_space(4.0);
        ui.label(format!(
            "Всё это идёт в сеть {} -> {:?} -> {} и выходит восемью числами. \
             Своего положения на карте особь не знает и памяти между шагами не имеет.",
            sim.brain.n_in, cfg.brain.hidden, sim.brain.n_out
        ));
    });

    section(ui, "Что особь решает", |ui| {
        ui.label(
            "Четыре выхода задают направление взгляда — куда особь смотрит, туда же \
             она идёт и туда же бьёт. Пятый выход спорит с ними: если он больше, \
             особь остаётся на месте.",
        );
        ui.add_space(4.0);
        ui.label("Оставшиеся три — это да или нет: есть, атаковать, размножиться.");
        ui.add_space(4.0);
        ui.label(
            "Атака и движение исключают друг друга. Иначе выгодной стала бы тактика \
             «ударил и убежал», а она ничего интересного не порождает.",
        );
    });

    section(ui, "Еда, рождение, смерть", |ui| {
        ui.label(format!(
            "За шаг особь съедает до {:.1} массы из своей клетки, сначала падаль, \
             потом растения. Больше {:.0} энергии в себя не вмещает.",
            a.eat_rate, a.max_energy
        ));
        ui.add_space(4.0);
        ui.label(format!(
            "Накопив {:.0}, особь может родить. Потомок получает {:.0}% её энергии, \
             ещё {:.0}% теряется в клетку, и ему достаётся копия сети родителя \
             с гауссовым шумом {:.3} в каждом весе.",
            a.repro_threshold,
            a.repro_share * 100.0,
            a.repro_overhead * 100.0,
            a.mutation_sigma
        ));
        ui.add_space(4.0);
        ui.label(format!(
            "Жизнь стоит {:.2} энергии за шаг, движение — ещё {:.2}. С возрастом \
             расход растёт на {:.4} за каждый прожитый шаг: это старение, \
             и оно гарантирует смену поколений даже в сытом мире.",
            a.metabolism, a.move_cost, a.age_cost_rate
        ));
        ui.add_space(4.0);
        ui.label(format!(
            "Опустившись до {:.1}, особь умирает, и вся её энергия ложится падалью \
             в ту клетку, где она стояла.",
            a.death_energy
        ));
    });

    section(ui, "Хищничество", |ui| {
        ui.label(
            "Хищников как вида нет. Атаковать может кто угодно кого угодно, \
             и если охота возникает, то сама — потому что оказалась выгодной.",
        );
        ui.add_space(4.0);
        ui.label(format!(
            "Удар снимает с соседа до {:.0} энергии и стоит атакующему {:.1} — \
             столько же платит и промах по пустой клетке.",
            a.attack_damage, a.attack_cost
        ));
        ui.add_space(4.0);
        if a.attack_yield > 0.0 {
            ui.label(format!(
                "{:.0}% снятого достаётся атакующему сразу, как укус; \
                 остальное падает падалью, и подобрать её может кто угодно.",
                a.attack_yield * 100.0
            ));
        } else {
            ui.label(
                "Атакующему не достаётся ничего: всё снятое падает падалью в клетку \
                 жертвы, и чтобы поесть, надо ещё дойти туда следующим ходом.",
            );
        }
        ui.add_space(4.0);
        ui.label(
            "Главный вопрос здесь — целятся ли особи. «Наводка» в управлении делит \
             долю попавших атак на плотность населения: единица означает, что бьют \
             вслепую, больше единицы — что перед ударом смотрят.",
        );
        ui.add_space(4.0);
        ui.label(
            "На значениях по умолчанию охота разворачивается не сразу. Первые тысячи \
             шагов наводка держится около единицы, затем медленно растёт и к 25 000 \
             шагов доходит примерно до 1,7, а доля животной пищи — до 40%. \
             Средний возраст при этом падает почти вдвое: охота ускоряет смену поколений.",
        );
        ui.add_space(4.0);
        ui.label(
            "Цена удара — единственное, что заставляет целиться, и она же легко всё \
             ломает. Сделайте её меньше — начнут бить вслепую, потому что в среднем \
             окупается. Сделайте сильно больше — охота поднимется и погаснет: \
             промахи съедят охотников раньше, чем окупится меткость.",
        );
    });

    section(ui, "Родословная и виды", |ui| {
        ui.label(
            "Дерево предков хранит только тех, у кого остались живые потомки. \
             Ветвь без потомства удаляется сразу, иначе за сотню тысяч шагов \
             накопились бы миллионы мёртвых узлов.",
        );
        ui.add_space(4.0);
        ui.label(
            "«Выживших линий» — сколько особей-основателей дали потомство, дожившее \
             до сейчас. Их число быстро падает: из двух тысяч остаются единицы. \
             Если линия одна, у всех живых есть последний общий предок, и видно, \
             в каком поколении он жил.",
        );
        ui.add_space(4.0);
        ui.label(
            "Расстояние между геномами меряется в мутационных шагах — в том, \
             которое геном проходит за одно рождение. Виды, если бы они возникли, \
             проявились бы как несколько сопоставимых кластеров, устойчивых \
             к порогу склейки. Пока такого не наблюдается: при любом пороге \
             либо множество мелких групп, либо одна большая.",
        );
    });

    section(ui, "Цвета на карте", |ui| {
        ui.label(
            "Клетка светится зелёным по растениям, красным по падали и даёт \
             синеватую подложку по питательным веществам. Выеденная земля почти чёрная.",
        );
        ui.add_space(4.0);
        ui.label(
            "Особей можно красить по линии, энергии, возрасту или поколению. \
             Раскраска по линии самая полезная: родственники получают один оттенок, \
             и видно, как удачная линия расползается пятном по карте, \
             а неудачные гаснут.",
        );
    });

    section(ui, "Графики", |ui| {
        g(ui, "численность", "сколько особей живо. Ровная линия — равновесие, падение до нуля — вымирание, прижатая к потолку — упор в ёмкость");
        g(ui, "биомасса в особях", "какую долю всей массы мира популяция держит в себе. Чем выше, тем эффективнее она использует мир");
        g(ui, "средний возраст", "короткий возраст означает быстрый оборот поколений, а значит быструю эволюцию");
        g(ui, "растительная масса", "запас корма. Провал здесь обычно предшествует провалу численности");
        g(ui, "еда на особь", "сколько раз за шаг средняя особь успевает поесть. Падает, когда корма не хватает на всех");
        g(ui, "животная пища", "какую долю съеденного составляют укусы и падаль. Это и есть ответ, кормит ли охота");
    });

    section(ui, "На что смотреть", |ui| {
        bullet(ui, "Вымирание в первые тысячи шагов: мало корма или слишком редкая стартовая посадка");
        bullet(ui, "Численность упёрлась в ёмкость: мир слишком богат, метрики перестают что-либо значить");
        bullet(ui, "Застой: одна линия захватила карту, цвета сошлись к одному оттенку, разнообразие кончилось");
        bullet(ui, "Жертвы кончились, за ними хищники: атака слишком сильна");
        bullet(ui, "Ничего не меняется многие тысячи шагов: стоит открыть особь и проверить, что её сенсоры вообще не пустые");
    });

    section(ui, "Воспроизводимость", |ui| {
        ui.label(format!(
            "Сид сейчас {}. Один и тот же сид даёт побитово один и тот же прогон: \
             порядок действий фиксирован, генератор случайных чисел свой, \
             а системный tanh заменён аппроксимацией, потому что он различается \
             между платформами.",
            cfg.seed
        ));
        ui.add_space(4.0);
        ui.label(format!(
            "Скорость роста растений {:.3}, потолок в клетке {:.1}, разложение падали {:.3}, \
             диффузия питательных веществ {:.3}.",
            r.growth_rate, r.plant_capacity, r.carrion_decay, r.nutrient_diffusion
        ));
    });
}

fn section(ui: &mut egui::Ui, title: &str, body: impl FnOnce(&mut egui::Ui)) {
    egui::CollapsingHeader::new(title)
        .default_open(false)
        .show(ui, body);
    ui.add_space(2.0);
}

fn bullet(ui: &mut egui::Ui, text: &str) {
    ui.horizontal_top(|ui| {
        ui.label("·");
        ui.label(text);
    });
}

fn numbered(ui: &mut egui::Ui, n: u32, text: &str) {
    ui.horizontal_top(|ui| {
        ui.monospace(format!("{n}."));
        ui.label(text);
    });
}

fn g(ui: &mut egui::Ui, name: &str, text: &str) {
    ui.horizontal_top(|ui| {
        ui.strong(name);
        ui.label(format!("— {text}"));
    });
}
